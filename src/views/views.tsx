interface AnalyzeProps {
  findings: Finding[];
  resolved: Record<string, number>;
  onResolve: (id: string, option: number) => void;
  role: Role;
}

export function AnalyzeView({ findings, resolved, onResolve, role }: AnalyzeProps) {
  const open = findings.filter(f => resolved[f.id] === undefined);
  const blocking = open.filter(f => f.sev === 'HIGH' || f.sev === 'CRITICAL').length;
  const canAct = role === 'QA' || role === 'Engineer';
  const total = SK.spec.frs.length + 1;
  return <div>
    <DocHead file="analysis report" title="Consistency analysis" meta="Read-only check across spec.md, plan.md and tasks.md" />
    <div className="sk-stats">
      <div><span>Requirements covered</span><b>{resolved.A1 === 0 ? `${total} / ${total}` : `${total - 1} / ${total}`}</b></div>
      <div><span>Open findings</span><b>{open.length}</b></div>
      <div className={blocking ? 'warn' : ''}><span>Blocking gate</span><b>{blocking}</b></div>
      <div><span>Constitution</span><b>Pass</b></div>
    </div>
    <section className="sk-sec"><Label>Findings</Label>
      {findings.map(f => <article key={f.id} className={'sk-finding' + (resolved[f.id] !== undefined ? ' is-res' : '')}>
        <div className="sk-finding-h">
          <span className={'tag ' + (f.sev === 'HIGH' || f.sev === 'CRITICAL' ? 'tag-accent' : f.sev === 'MEDIUM' ? 'tag-outline' : 'tag-neutral')}>{f.sev}</span>
          <span className="sk-id">{f.id}</span><b>{f.cat}</b><span className="sk-path">{f.loc}</span>
        </div>
        <p>{f.d}</p>
        {resolved[f.id] !== undefined
          ? <div className="sk-pass"><Icon n="check" s={14} />Resolved: {f.opts[resolved[f.id]]}</div>
          : <div className="sk-actions">{f.opts.map((o, i) => <button key={i} className={'btn ' + (i === 0 ? 'btn-secondary' : 'btn-ghost')} disabled={!canAct} onClick={() => onResolve(f.id, i)}>{o}</button>)}</div>}
      </article>)}
      {!canAct && <p className="text-muted sk-sm">Findings are resolved by QA or Engineer. Switch role to act.</p>}
    </section>
  </div>;
}

interface ImplementProps {
  locked: boolean;
  tasks: Task[];
  done: Record<string, boolean>;
  onToggle: (id: string) => void;
  role: Role;
  qa: Record<string, QaResult>;
  onQa: (key: string, v: QaResult) => void;
}

export function ImplementView({ locked, tasks, done, onToggle, role, qa, onQa }: ImplementProps) {
  if (locked) return <div className="sk-empty">
    <Icon n="lock" s={28} />
    <h4>Implement unlocks when Analyze is approved</h4>
    <p>{tasks.length} tasks are queued. QA, Engineer and Director must approve the analysis, with no HIGH findings open.</p>
  </div>;
  const n = tasks.filter(t => done[t.id]).length;
  return <div>
    <DocHead file="branch 003-transfer-limits" title="Implementation" meta={`${n} of ${tasks.length} tasks complete · tasks are checked off as /speckit.implement or the owner finishes them`} />
    <div className="sk-progress" role="progressbar" aria-valuemin={0} aria-valuemax={tasks.length} aria-valuenow={n}><div style={{ width: (n / tasks.length * 100) + '%' }}></div></div>
    <TaskTable tasks={tasks} done={done} onToggle={onToggle} canToggle={t => t.o === role || role === 'Engineer'} />
    <section className="sk-sec"><Label>Acceptance verification · QA</Label>
      <table className="table"><tbody>{SK.spec.stories.flatMap(u => u.ac.map((a, i) => {
        const k = u.id + '-' + i;
        return <tr key={k}><td className="sk-id" style={{ width: 70 }}>{u.id}.{i + 1}</td><td>Given {a[0]}, then {a[2]}.</td>
          <td style={{ width: 150 }}><div className="seg">{(['Pass', 'Fail'] as const).map(v => <button key={v} className={'seg-opt sk-segbtn' + (qa[k] === v ? ' on' : '')} disabled={role !== 'QA'} onClick={() => onQa(k, v)} aria-pressed={qa[k] === v}>{v}</button>)}</div></td></tr>;
      }))}</tbody></table>
    </section>
  </div>;
}

export function SummaryView({ feature, phase, status }: { feature: Feature; phase: Phase; status: PhaseStatus }) {
  const st = status === 'done' ? 'Approved' : status === 'review' ? 'In review' : 'Not started';
  if (feature.draft && phase.k === 'specify') return <div>
    <DocHead file={`specs/${feature.slug}/spec.md`} title="Feature specification" meta={`Draft · awaiting ${phase.gate.join(' and ')}`} />
    <DraftSpec draft={feature.draft} />
  </div>;
  if (status === 'locked') return <div className="sk-empty"><Icon n="lock" s={28} /><h4>{phase.n} has not started</h4><p>It opens when the previous gate is approved, then <b>{phase.cmd}</b> generates {phase.file}.</p></div>;
  return <div>
    <DocHead file={`specs/${feature.slug}/${phase.file}`} title={`${phase.n} · ${feature.title}`} meta={st} />
    <p style={{ maxWidth: 640 }}>{feature.summary}</p>
    {!feature.draft && <p className="text-muted sk-sm">Open feature 003 to see full artifacts in this prototype.</p>}
  </div>;
}
